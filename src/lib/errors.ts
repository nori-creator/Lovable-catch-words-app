/**
 * サーバーから来たエラーを、画面に出していいものかどうかで振り分ける。
 *
 * ## なぜ要るか
 * 生のメッセージをそのまま出すと `fetch failed` や `PGRST116` が画面に
 * 並ぶ。日本語で使っている人には何も分からないし、対処もできない。
 *
 * かといって全部まとめて「失敗しました」に潰すのも間違いだった。
 * こちらが自分で投げている「1日の利用上限(300回)に達しました」は、
 * **理由も対処も分かる**メッセージで、これを潰すとユーザーは
 * 二度と直らないものを押し続けることになる(独立監査の指摘)。
 *
 * 判定は「読み手の言葉で書かれているか」で行う。日本語の文字が
 * 入っていれば、こちらが人に向けて書いたものとみなす。
 */
export function readableError(e: unknown, fallback: string): string {
  const msg = e instanceof Error ? e.message : "";
  if (!msg) return fallback;
  // ひらがな・カタカナ・漢字のいずれかを含む = 人に向けて書かれた文。
  if (/[぀-ヿ一-龯]/.test(msg)) return msg;
  return fallback;
}
