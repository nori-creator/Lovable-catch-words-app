/**
 * 件数の書き方を1箇所に決める。
 *
 * ## なぜ要るか
 * 同じ「件数」が画面ごとに5通りで出ていた:
 *
 *   — 6 枚の思い出        数字の前後に空き・ダッシュ前置き
 *   解析待ちの写真: 2      半角コロン・助数詞なし
 *   3枚                   正しい形
 *   全 1342 件のうち       空き + 三桁区切りなし
 *   再会 3 回目            空き
 *
 * **和文では数字と助数詞の間を空けない。** 空けると「6」と「枚」が別の語に
 * 見える。三桁区切りも入れないと、4桁を超えた瞬間に読めなくなる。
 *
 * 助数詞そのものは i18n の文言側が持つ(言語ごとに位置も有無も変わる)。
 * ここが決めるのは**数の書き方だけ**。
 */

/**
 * 件数を表示用の文字列にする。
 *
 * 表示にしか使わないので、**壊れた数でも決して投げない** — 数が出ない
 * ことと画面が落ちることは重さが違う。整数でないものは丸める。
 */
export function formatCount(n: number, locale = "ja-JP"): string {
  if (!Number.isFinite(n)) return "0";
  const v = Math.max(0, Math.round(n));
  try {
    return v.toLocaleString(locale);
  } catch {
    // 知らない locale を渡されても落とさない。
    return String(v);
  }
}
