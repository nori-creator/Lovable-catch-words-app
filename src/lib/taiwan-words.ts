/** 見出し語の台湾の言い方（表に無ければそのまま）。 */
export function taiwanHeadword(headword: string): string {
  const h = (headword ?? "").trim();
  return MAINLAND_TO_TAIWAN[h] ?? headword;
}

/**
 * 候補の見出し語を台湾の言い方にする。置き換えた候補は読みを空にする（後で辞書が作る）。置き換えた結果、同じ物
 * （同じ group）の前の候補と同じ語になった物は落とす（塑膠袋 と 塑料袋 → 塑膠袋 を2つ出さない）。
 */
export function toTaiwanWords<
  T extends { headword: string; group?: number | null; pinyin?: string; reading_zhuyin?: string },
>(items: readonly T[]): T[] {
  const out: T[] = [];
  for (const it of items) {
    const tw = taiwanHeadword(it.headword);
    const next: T =
      tw === it.headword ? it : { ...it, headword: tw, pinyin: "", reading_zhuyin: "" };
    const group = next.group ?? null;
    if (out.some((o) => o.headword === next.headword && (o.group ?? null) === group)) continue;
    out.push(next);
  }
  return out;
}
