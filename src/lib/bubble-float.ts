/**
 * 札の**浮遊感**を決める値。位置は決めない。
 *
 * ## オーナー指示 2026-08-28 ①
 * > 「カテゴリーがランダムに並んでいるから修正して。私が浮遊感と言ったのは、
 * >  影や奥行きタップした時のバウンス感など物理法則によってそのカテゴリーが
 * >  浮遊してるようにふわふわしてるいう意味です。カテゴリーはちゃんと
 * >  整列させて。」
 *
 * ## 前のやり方の何が違ったか
 * 前は札を面の中に**自由に飛ばして**いた。位置そのものを物理で決めたので、
 * 並びが毎回変わり、読む順も無くなった。求められていたのは「浮いている
 * ように**見える**」ことで、「浮いて動き回る」ことではなかった。
 *
 * だから位置は**整列**（行に流す）に戻し、浮遊感は3つで出す:
 *   ① 影と奥行き … 札ごとにわずかに違う高さに置く
 *   ② ふわふわ   … ゆっくり上下に揺れる（振れ幅は数 px）
 *   ③ 弾み       … 押した瞬間に沈んで、離すとばねで戻る
 *
 * ## なぜ純粋な物として出すか
 * 「札ごとに少しずつ違う」を乱数で作ると、**描き直すたびに揺れ方が
 * 変わって**画面がざわつく。同じ札には必ず同じ値が出るよう、札の名前から
 * 決める。ここが試験で縛れるので、絵の検査も毎回同じ絵になる。
 */

/** 浮きの段。0=いちばん低い(影が薄い) … 2=いちばん高い(影が濃い)。 */
export type FloatDepth = 0 | 1 | 2;

export type FloatStyle = {
  /** 揺れ始めをずらす(ms)。全部が同時に上下すると板に見える。 */
  delayMs: number;
  /** 1往復の時間(ms)。長いほどゆっくり。 */
  durationMs: number;
  /** 上下の振れ幅(px)。**小さく**保つ — 大きいと行が崩れて見える。 */
  liftPx: number;
  depth: FloatDepth;
};

/** 揺れの速さの幅。速すぎると落ち着かず、遅すぎると止まって見える。 */
export const DURATION_MIN_MS = 3200;
export const DURATION_MAX_MS = 5200;
/** 振れ幅の上限。これを超えると隣の行に触れる。 */
export const MAX_LIFT_PX = 4;

/** 文字列 → 32bit の数。同じ字なら必ず同じ数。 */
function hash(s: string): number {
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 16777619) >>> 0;
  }
  return h >>> 0;
}

/**
 * その札の浮き方。**同じ札なら必ず同じ**。
 *
 * `index` も混ぜる — 同じ字の札が2つ並ぶことは無いが、束を跨いで
 * 近い名前が並んだときに、揺れが揃って見えるのを避ける。
 */
export function floatStyle(id: string, index = 0): FloatStyle {
  const h = hash(`${id}#${index}`);
  const span = DURATION_MAX_MS - DURATION_MIN_MS;
  return {
    delayMs: h % 1400,
    durationMs: DURATION_MIN_MS + ((h >>> 11) % (span + 1)),
    // 2〜4px。0 にしない — 1つだけ止まって見える札を作らない。
    liftPx: 2 + ((h >>> 19) % (MAX_LIFT_PX - 1)),
    depth: ((h >>> 25) % 3) as FloatDepth,
  };
}
