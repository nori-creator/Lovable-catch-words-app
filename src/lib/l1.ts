export type L1Phonology = {
  /** 子音(声母)の干渉。有気/無気・そり舌・f/h など。 */
  consonants: string;
  /** 韻母の干渉。鼻音韻尾 -n/-ng、ㄩ(ü)、母音の数。 */
  finals: string;
  /** 声調の干渉。母語の韻律が声調をどう壊すか。 */
  tones: string;
  /** 音節構造とリズム。促音・強勢・末子音の解放など。 */
  prosody: string;
  /** その母語だから**有利**な点。潰さずに活かすために明示する。 */
  advantages: string;
};

export type L1Grammar = {
  /** 語順(基本語順・修飾の向き・副詞や時間場所の位置)。 */
  wordOrder: string;
  /** 時制とアスペクト(了/過/在/著 の扱い)。 */
  aspect: string;
  /** 量詞。 */
  measureWords: string;
  /** 助詞・助辞(的/得/地、嗎/吧/呢)。 */
  particles: string;
  /** 否定(不/沒)。 */
  negation: string;
  /** よく崩れる構文(把/被/是…的/比/離合詞 など)。 */
  patterns: string;
  /** 語彙レベルの罠。同形異義語・偽の友。 */
  falseFriends: string;
};

export type L1Info = {
  code: L1Code;
  /** 日本語での言語名(管理・ログ用)。UI表示は i18n キー側で持つ。 */
  labelJa: string;
  labelEn: string;
  /** プロンプトに書く話者の呼び方(例「日本語話者」)。 */
  speakerJa: string;
  speakerEn: string;
  /**
   * 通じなくなる順の上位3つ。限られた文字数のアドバイスを
   * 致命傷から埋めさせるために、平らな項目リストとは別に持つ。
   */
  priority: string[];
  phonology: L1Phonology;
  grammar: L1Grammar;
  /** 台湾華語ならではの事情が、この母語話者にどう効くか。 */
  taiwan: string;
};

