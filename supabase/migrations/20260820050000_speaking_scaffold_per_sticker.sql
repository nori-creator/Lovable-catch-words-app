-- 2026-08-20
-- スピーキングの足場を**その1枚ごと**に持たせる。
--
-- ## なぜ要るか
-- 要望(2026-08-18):
-- 「スピーキングの復習のときは、ユーザーに質問をする。質問はユーザーの内面の
--  気持ち、思い出、感情、個人的な情報を引き出すようにAIが考える。そのうえで
--  自分の撮った時の感想、一言をもとに型やフレーズ、語法のヒントを表示。」
--
-- ところが `getSpeakingScaffold` は caption も場所も日付もプロンプトに
-- 渡していなかった。プロンプトには「写真の状況に沿った質問」と書いてあるのに、
-- **その状況を1文字も渡していない**ので、ずっと空振りしていた。
--
-- ## なぜ列を足すのか — 混ぜると他人に漏れる
-- 足場は `words.extras` に**語単位**でキャッシュされていた。
-- `words` は利用者どうしで共有される表なので、そこへ「その人が撮ったときの
-- 一言」から作った質問を書き込むと、**同じ語を持つ別の利用者にその人の
-- 思い出が出る**。個人の記憶を混ぜてよい場所ではない。
--
-- だから足場は `stickers`(その人の1枚)に置く。
-- 語単位の古いキャッシュ(`words.extras.speaking_scaffold_v*`)はそのまま
-- 残しておく — 消すのは破壊で、読まなくなれば害は無い。

alter table public.stickers add column if not exists speaking_scaffold jsonb;

comment on column public.stickers.speaking_scaffold is
  'スピーキング復習の足場(質問+ヒント)。撮ったときの一言・場所・日付から作るので、'
  '語ではなく**この1枚**に紐づく。中身は { key, scaffold } で、key には表示言語・'
  '母語・一言の指紋が入る — どれかが変われば作り直す。';
